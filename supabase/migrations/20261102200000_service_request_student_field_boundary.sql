-- Protect request creation and student-visible fields without replacing the
-- existing student workflow. Inventory legacy/external clients and hosted RLS
-- policies before staging; this migration must not be applied blindly.
begin;

-- Admin queue reads go through the capability-checked service-role API.
drop policy if exists service_requests_read_staff on public.service_requests;
drop policy if exists service_requests_read_own on public.service_requests;
create policy service_requests_read_own on public.service_requests
for select to authenticated using (user_id = (select auth.uid()));

drop policy if exists service_requests_insert_own on public.service_requests;
create policy service_requests_insert_own on public.service_requests
for insert to authenticated with check (
  user_id = (select auth.uid()) and status = 'submitted'
  and exists (select 1 from public.service_catalog sc where sc.id = service_requests.service_id and sc.active is true)
);

-- Unknown permissive SELECT/INSERT/ALL policies can OR around the owner policy.
-- Abort rather than delete unreviewed hosted policies or silently allow access.
do $$
begin
  if exists (
    select 1 from pg_policy p
    where p.polrelid = 'public.service_requests'::regclass
      and p.polcmd in ('r', 'a', '*')
      and p.polname not in ('service_requests_read_own', 'service_requests_insert_own')
      and exists (
        select 1 from unnest(p.polroles) as role_ids(role_id)
        where case when role_id = 0::oid then true
          else pg_has_role('anon', role_id, 'MEMBER') or pg_has_role('authenticated', role_id, 'MEMBER') end
      )
  ) then
    raise exception 'unreviewed client SELECT/INSERT service_requests policy; inspect policy and role membership before retrying';
  end if;
end
$$;

revoke select, insert on table public.service_requests from public, anon, authenticated;
do $$
declare
  columns_sql text;
begin
  select string_agg(format('%I', attname), ', ' order by attnum) into columns_sql
  from pg_attribute
  where attrelid = 'public.service_requests'::regclass and attnum > 0 and not attisdropped;
  execute format('revoke select (%1$s), insert (%1$s) on public.service_requests from public, anon, authenticated', columns_sql);
end
$$;

-- Explicit allowlists prevent both spoofing server-managed fields and exposing
-- future columns by default. Reference and timestamps are generated by the DB.
grant select (id, user_id, service_id, status, form_data, reference_code, created_at)
  on public.service_requests to authenticated;
grant insert (user_id, service_id, status, form_data)
  on public.service_requests to authenticated;

do $$
begin
  if has_table_privilege('anon', 'public.service_requests', 'SELECT')
     or has_table_privilege('anon', 'public.service_requests', 'INSERT')
     or has_table_privilege('authenticated', 'public.service_requests', 'SELECT')
     or has_table_privilege('authenticated', 'public.service_requests', 'INSERT')
     or exists (
       select 1 from pg_attribute a
       where a.attrelid = 'public.service_requests'::regclass and a.attnum > 0 and not a.attisdropped
         and (has_column_privilege('anon', a.attrelid, a.attname, 'SELECT')
           or has_column_privilege('anon', a.attrelid, a.attname, 'INSERT')
           or (a.attname <> all(array['id','user_id','service_id','status','form_data','reference_code','created_at'])
               and has_column_privilege('authenticated', a.attrelid, a.attname, 'SELECT'))
           or (a.attname <> all(array['user_id','service_id','status','form_data'])
               and has_column_privilege('authenticated', a.attrelid, a.attname, 'INSERT')))
     ) then
    raise exception 'service_requests client field access remains available through inherited grants; review role membership before retrying';
  end if;
end
$$;
commit;
