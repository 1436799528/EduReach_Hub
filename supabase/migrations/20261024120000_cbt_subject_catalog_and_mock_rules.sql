-- CBT subject catalogue and exam-specific combination limits.
-- This stores subject metadata only; it deliberately does not fabricate question content.
create table if not exists public.cbt_subject_catalog (
  id bigint generated by default as identity primary key,
  exam_body text not null check (exam_body in ('JAMB','WAEC','NECO','POST-UTME')),
  subject_name text not null,
  subject_group text not null check (subject_group in ('Science','Arts','Commercial','Technical & Vocational')),
  active boolean not null default true,
  created_at timestamptz not null default now(),
  unique (exam_body, subject_name, subject_group)
);

