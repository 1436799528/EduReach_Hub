-- WAEC/NECO allow up to nine selected subjects in a practice setup. The mock
-- must use a full nine-subject combination. JAMB remains four subjects exactly
-- for a mock, with Use of English included. Practice sessions remain flexible.
create or replace function public.cbt_limits()
returns jsonb
language sql
immutable
as $fn$
  select jsonb_build_object(
    'minQuestions', 5,
    'maxQuestions', 100,
    'minMinutes', 5,
    'maxMinutes', 240,
    'maxSubjects', 9
  );
$fn$;

create or replace function public.enforce_cbt_subject_combination()
returns trigger
language plpgsql
security definer
set search_path = ''
as $fn$
declare
  v_body text;
  v_count integer;
  v_has_english boolean;
begin
  select upper(trim(e.exam_body)) into v_body
  from public.cbt_exams e
  where e.id = new.exam_id;

  select count(distinct public.cbt_subject_key(s)), bool_or(public.cbt_subject_key(s) = 'english')
    into v_count, v_has_english
  from unnest(coalesce(new.selected_subjects, '{}'::text[])) as s
  where trim(s) <> '';

  if v_body = 'JAMB' then
    if v_count > 4 then
      raise exception 'A JAMB session can include at most four subjects.';
    end if;
    if not coalesce(v_has_english, false) then
      raise exception 'Use of English is compulsory for JAMB UTME.';
    end if;
    if lower(trim(coalesce(new.mode, 'practice'))) = 'mock' and v_count <> 4 then
      raise exception 'A JAMB mock requires exactly four subjects, including Use of English.';
    end if;
  elsif v_body in ('WAEC','NECO') then
    if v_count > 9 then
      raise exception 'A % session can include at most nine subjects.', v_body;
    end if;
    if lower(trim(coalesce(new.mode, 'practice'))) = 'mock' and v_count <> 9 then
      raise exception 'A % mock requires exactly nine selected subjects.', v_body;
    end if;
  elsif lower(trim(coalesce(new.mode, 'practice'))) = 'mock' and v_count < 4 then
    raise exception 'A mock requires at least four subjects. Use practice mode for a shorter session.';
  end if;
  return new;
end;
$fn$;

drop trigger if exists enforce_cbt_subject_combination on public.cbt_attempts;
create trigger enforce_cbt_subject_combination
  before insert or update of exam_id, selected_subjects, mode
  on public.cbt_attempts
  for each row execute function public.enforce_cbt_subject_combination();
